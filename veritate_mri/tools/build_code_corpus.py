# Notes:
# - Builds the code byte-level corpora (python, javascript, html, css, coding Q&A,
#   and the mixed_code experimental variants) shipped to Mirach-Corpuses.
# - Two phases. `stage` pulls source documents to a local jsonl cache (network);
#   `build` assembles bins from the cache (offline, deterministic from a seed).
# - Sources, all pinned to fixed revisions so rebuilds are byte-identical:
#     py/js: HuggingFaceTB/stack-edu metadata (education-classifier scored), file
#            content fetched anonymously from the public Software Heritage S3.
#     html/css: curated permissive-license GitHub repos, tarballs by pinned ref.
#     qa: donfu/oa-stackexchange, stackoverflow rows filtered to coding tags and
#         vote thresholds, framed as ChatML per documentation.md (corpus framing).
# - Code families emit autocomplete mode: raw files joined by <|endoftext|>.
#   qa emits chat mode (ChatML). Val split is a stable 2% hash bucket per doc.
# - mixed_* build variants for the corpus-style ablation:
#     mixed_raw   size caps + exact dedup only (control)
#     mixed_files full filters + near-dedup, score>=3
#     mixed_edu   full filters + near-dedup, score>=4 (textbook tier)
#     mixed_qa    mixed_files pool 50% + Q&A 50%
# - Run:
#     python veritate_mri/tools/build_code_corpus.py stage --family py --target-mb 1300
#     python veritate_mri/tools/build_code_corpus.py build --family py \
#       --out-train py_code_1gb_train.bin --out-val py_code_1gb_val.bin --target-mb 1000
# veritate_mri/tools/build_code_corpus.py
