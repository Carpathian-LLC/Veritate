# ----------------------------- Build --------------------------------------

def pick(pool_u, pool_a, n, seen_pairs):
    out = []
    tries = 0
    while len(out) < n and tries < n * 60:
        tries += 1
        u = random.choice(pool_u)
        a = random.choice(pool_a)
        key = (u.lower(), a.lower())
        if key in seen_pairs:
            continue
        if not ok(a):
            continue
        seen_pairs.add(key)
        out.append({"user": u, "assistant": a})
    while len(out) < n:
        u = random.choice(pool_u)
        a = random.choice(pool_a)
        if ok(a):
            out.append({"user": u, "assistant": a})
    return out


seen = set()
family1 = pick(user_greetings_casual, assistant_greetings, 500, seen)
family2 = pick(user_hru, assistant_hru, 500, seen)
family3 = pick(user_smalltalk, assistant_smalltalk, 500, seen)
family4 = pick(user_disclose, assistant_disclose, 500, seen)

# Sprinkle ~60 honest-bot pairs across families 1 and 2 to enforce
# the "honest but not preachy" line.
random.shuffle(honest_bot_pairs)
inject_count = min(60, len(honest_bot_pairs))
half = inject_count // 2
for i in range(half):
    pair = honest_bot_pairs[i]
    family1[-(i + 1)] = {"user": pair[0], "assistant": pair[1]}
for i in range(inject_count - half):
    pair = honest_bot_pairs[half + i]
    family2[-(i + 1)] = {"user": pair[0], "assistant": pair[1]}

all_pairs = family1 + family2 + family3 + family4
assert len(all_pairs) == 2000, f"got {len(all_pairs)}"

for p in all_pairs:
    assert ok(p["assistant"]), p

